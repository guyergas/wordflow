// The English ABC for children of five and six who do not read yet. Capitals come first and small letters follow,
// grouped by shape as in the alef-bet: straight lines, then slanted ones, then curves. Spoken Hebrew carries vowel marks.
import { Pt, Shape, Stroke } from '../alef/letters';

const L = (...c: number[]): Stroke => ({ k: 'big', p: c.reduce<Pt[]>((a, v, i) => (i % 2 ? a : [...a, [v, c[i + 1]] as Pt]), []) });
const arcPts = (cx: number, cy: number, rx: number, ry: number, from: number, to: number): Pt[] => {
  const n = Math.max(6, Math.ceil(Math.abs(to - from) / 15));
  return Array.from({ length: n + 1 }, (_, i): Pt => { const a = ((from + ((to - from) * i) / n) * Math.PI) / 180; return [Math.round((cx + rx * Math.sin(a)) * 10) / 10, Math.round((cy - ry * Math.cos(a)) * 10) / 10]; });
};
const A = (cx: number, cy: number, rx: number, ry: number, from: number, to: number): Stroke => ({ k: 'round', p: arcPts(cx, cy, rx, ry, from, to) });
/** One stroke made of straight parts and curves. */
const J = (...parts: (Pt[])[]): Stroke => ({ k: 'round', p: parts.flat() });
const P = (x: number, y: number): Pt[] => [[x, y]];

export interface AbcLetter extends Shape { id: string; big: boolean; family: number; recipe: string }
const c = (id: string, family: number, strokes: Stroke[], recipe: string): AbcLetter => ({ id, big: id === id.toUpperCase(), family, strokes, recipe });

