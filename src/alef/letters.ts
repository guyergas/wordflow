/** Letters that are easily mixed up, so that the games teach the difference. */
const LOOK_ALIKE = ['יון', 'וןזג', 'רדך', 'דהח', 'חתה', 'רקך', 'כבנ', 'פףכ', 'םסט', 'םמס', 'עצץ', 'אעש', 'גנז', 'לך'];
export function lookAlikes(id: string): string[] {
  return [...new Set(LOOK_ALIKE.filter((g) => g.includes(id)).join('').split('').filter((c) => c !== id))];
}

